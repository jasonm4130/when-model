import type { LabId } from './lab';

/**
 * P(some frontier lab ships a text model within h hours), from per-lab market reads. Pure.
 *
 * The event is the one the calibration study scored (scripts/backtest/replay.ts,
 * data/backtest/v3-replay.json): a frontier lab (FRONTIER_LABS) has a text-output OpenRouter release
 * event (`releaseEvents`) whose first listing falls in (now, now + h]. Markets price named
 * releases; most launches are not named in advance, so the forecast is a noisy-OR of every lab's
 * market read and an "unpriced release" term fitted on history:
 *
 *   p = 1 − (1 − u(h)) · Π_lab (1 − p_lab),  then optionally σ(a + b · logit(p)).
 *
 * The study's verdict is in `FORECAST_CONSTANTS.recommendation`. It came back `lead-score`: at 72h no
 * formula beat the train-window base rate out of sample, so `p` is context for the page (base-rate
 * line, /backtest), not the DROPCON headline.
 */

/** Fitted values for one horizon, and how the shipped formula scored on the held-out window. */
export interface HorizonConstants {
  horizonHours: number;
  /** u: P(a frontier release no market prices) within the horizon, fitted by maximum likelihood on train. */
  unpriced: number;
  /** Logistic recalibration p' = σ(a + b·logit(p)); `{ a: 0, b: 1 }` is the identity. */
  calibration: { a: number; b: number };
  /** Share of train-window hours in which a frontier release landed within the horizon: formula (a). */
  baseRate: number;
  /** The shipped formula on the test window. Skill is Brier skill vs `baseRate`; the interval is a block bootstrap. */
  test: {
    hours: number;
    rate: number;
    brier: number;
    skill: number;
    skillCi95: [number, number];
    /** Calibration in the large within 0.05 and every bin of ≥100 hours within 0.20. */
    sane: boolean;
  };
}

export interface ForecastConstants {
  version: number;
  /** (d) noisy-OR, or (e) noisy-OR plus logistic recalibration: the better of the two at 72h out of sample. */
  formula: 'noisy-or' | 'noisy-or-cal';
  /** What the study decided for the DROPCON v3 headline. */
  recommendation: 'probability' | 'lead-score';
  /** Train window and the distinct release events in it. */
  fittedOn: { from: string; to: string; events: number };
  /** Held-out window and the distinct release events in it: the effective sample size. */
  testedOn: { from: string; to: string; events: number };
  /** One entry per fitted horizon (24h, 72h, 7d), ascending. */
  horizons: readonly HorizonConstants[];
}

